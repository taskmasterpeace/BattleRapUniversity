// Read the mapping out of the DB (post-backfill) and emit a static SQL migration
// so the icon_url assignments survive supabase db reset.
import { createClient } from '@supabase/supabase-js';
import { config } from 'dotenv';
import { writeFileSync } from 'node:fs';

config({ path: '.env.local' });

const supabase = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL,
  process.env.SUPABASE_SERVICE_ROLE_KEY,
  { auth: { autoRefreshToken: false, persistSession: false } }
);

const { data: badges } = await supabase
  .from('badge_costs')
  .select('badge_code, icon_url')
  .order('badge_code');

const lines = [
  '-- Backfill icon_url for every badge in badge_costs.',
  '-- Mapping was generated by scripts/backfill-badge-icons.mjs which pairs badges',
  '-- (sorted by category, badge_name) with sprites (sorted by numeric suffix).',
  '-- Re-running the script can change paths if new badges are added — regenerate',
  '-- this migration via scripts/gen-badge-icon-migration.mjs after any change.',
  '',
];

for (const b of badges) {
  if (!b.icon_url) continue;
  lines.push(
    `UPDATE badge_costs SET icon_url = '${b.icon_url}' WHERE badge_code = '${b.badge_code}';`
  );
}

const sql = lines.join('\n') + '\n';
const outPath = 'supabase/migrations/20260521000000_backfill_badge_icon_urls.sql';
writeFileSync(outPath, sql);
console.log(`Wrote ${outPath} (${badges.length} updates)`);
