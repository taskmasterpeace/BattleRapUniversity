// Generate a static SQL migration from the current cities sprite mapping.
import { createClient } from '@supabase/supabase-js';
import { writeFileSync } from 'node:fs';
import { config } from 'dotenv';

config({ path: '.env.local' });

const supabase = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL,
  process.env.SUPABASE_SERVICE_ROLE_KEY,
  { auth: { autoRefreshToken: false, persistSession: false } }
);

const { data: cities } = await supabase
  .from('cities')
  .select('name, background_url, skyline_url')
  .order('name');

const lines = [
  '-- Backfill background_url and skyline_url on cities.',
  '-- Sprites under /public/sprites/cities/{region}/{slug}-{day|dusk|night}.png',
  '-- Generated by scripts/gen-city-sprite-migration.mjs (run after backfill-city-sprites.mjs).',
  '',
];

for (const c of cities) {
  if (!c.background_url && !c.skyline_url) continue;
  const bg = c.background_url ? `'${c.background_url}'` : 'NULL';
  const sky = c.skyline_url ? `'${c.skyline_url}'` : 'NULL';
  lines.push(
    `UPDATE cities SET background_url = ${bg}, skyline_url = ${sky} WHERE name = '${c.name.replace(/'/g, "''")}';`
  );
}

const path = 'supabase/migrations/20260522000000_backfill_city_sprite_urls.sql';
writeFileSync(path, lines.join('\n') + '\n');
console.log(`Wrote ${path} (${cities.filter(c => c.background_url).length} updates)`);
