// Read current badge_costs.icon_url and leagues.logo_url and emit static
// migration files so the remapped sprite assignments survive db reset.
import { createClient } from '@supabase/supabase-js';
import { writeFileSync } from 'node:fs';
import { config } from 'dotenv';

config({ path: '.env.local' });

const supabase = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL,
  process.env.SUPABASE_SERVICE_ROLE_KEY,
  { auth: { autoRefreshToken: false, persistSession: false } }
);

// Badges
const { data: badges } = await supabase
  .from('badge_costs')
  .select('badge_code, icon_url')
  .order('badge_code');

const badgeLines = [
  '-- Re-mapped badge icon_url based on baked-in sprite labels (semantic match).',
  '-- Generated by scripts/gen-icon-remap-migrations.mjs after scripts/remap-badge-icons.mjs.',
  '-- Supersedes 20260521000000_backfill_badge_icon_urls.sql.',
  '',
];
let bc = 0;
for (const b of badges) {
  if (!b.icon_url) continue;
  badgeLines.push(`UPDATE badge_costs SET icon_url = '${b.icon_url}' WHERE badge_code = '${b.badge_code}';`);
  bc++;
}
writeFileSync(
  'supabase/migrations/20260522010000_remap_badge_icon_urls.sql',
  badgeLines.join('\n') + '\n'
);
console.log(`Wrote badge remap migration (${bc} rows)`);

// Leagues
const { data: leagues } = await supabase
  .from('leagues')
  .select('short_code, logo_url')
  .order('short_code');

const leagueLines = [
  '-- Re-mapped league logo_url based on baked-in sprite labels (semantic match).',
  '-- Generated by scripts/gen-icon-remap-migrations.mjs after scripts/remap-league-logos.mjs.',
  '',
];
let lc = 0;
for (const l of leagues) {
  if (!l.logo_url) continue;
  leagueLines.push(`UPDATE leagues SET logo_url = '${l.logo_url}' WHERE short_code = '${l.short_code}';`);
  lc++;
}
writeFileSync(
  'supabase/migrations/20260522020000_remap_league_logo_urls.sql',
  leagueLines.join('\n') + '\n'
);
console.log(`Wrote league remap migration (${lc} rows)`);
