import { chromium } from '@playwright/test';
const BASE = process.env.BASE || 'http://localhost:1919';
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1 });
const page = await ctx.newPage();
await page.goto(`${BASE}/badges`);
await page.waitForLoadState('networkidle');
await page.waitForTimeout(1000);
await page.screenshot({ path: 'test-results/badges-full.png', fullPage: true });
console.log('Saved badges-full.png');
await browser.close();
