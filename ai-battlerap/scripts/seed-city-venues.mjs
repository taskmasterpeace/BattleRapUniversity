const emitSql = process.argv.includes('--emit-sql')
  ? process.argv[process.argv.indexOf('--emit-sql') + 1]
  : null;
const esc = (x) => String(x).replace(/'/g, "''");
const sql = [
  '-- City venue rosters (generated by scripts/seed-city-venues.mjs)',
  "DELETE FROM venues WHERE name LIKE '%(Default)' AND venue_type_id NOT IN (SELECT id FROM venue_types WHERE tier = 'virtual');",
];

const { data: types } = await supabase.from('venue_types').select('id, slug');
const typeBySlug = new Map(types.map((t) => [t.slug, t.id]));
const { data: cities } = await supabase.from('cities').select('id, name');
const cityByName = new Map(cities.map((c) => [c.name, c.id]));

// Clear the unwired physical defaults locally (keep virtual rooms for online leagues)
const { data: virtualTypes } = await supabase.from('venue_types').select('id').eq('tier', 'virtual');
const virtualIds = virtualTypes.map((v) => v.id);
await supabase
  .from('venues')
  .delete()
  .like('name', '%(Default)')
  .not('venue_type_id', 'in', `(${virtualIds.join(',')})`);

let inserted = 0;
for (const [cityName, roster] of Object.entries(ROSTERS)) {
  const cityId = cityByName.get(cityName);
  if (!cityId) {
    console.error(`no city: ${cityName}`);
    continue;
  }
  for (const [name, slug, prestige] of roster) {
    const typeId = typeBySlug.get(slug);
    if (!typeId) {
      console.error(`no venue type: ${slug}`);
      continue;
    }
    // Idempotent: skip if already seeded
    const { data: existing } = await supabase
      .from('venues')
      .select('id')
      .eq('name', name)
      .maybeSingle();
    if (!existing) {
      const { error } = await supabase.from('venues').insert({
        venue_type_id: typeId,
        city_id: cityId,
        name,
        prestige_level: prestige,
        is_active: true,
      });
      if (error) console.error(`${name}: ${error.message}`);
      else inserted++;
    }
    sql.push(
      `INSERT INTO venues (venue_type_id, city_id, name, prestige_level, is_active) ` +
        `SELECT vt.id, c.id, '${esc(name)}', ${prestige}, true FROM venue_types vt, cities c ` +
        `WHERE vt.slug = '${esc(slug)}' AND c.name = '${esc(cityName)}' ` +
        `AND NOT EXISTS (SELECT 1 FROM venues v WHERE v.name = '${esc(name)}');`
    );
  }
}

if (emitSql) fs.writeFileSync(emitSql, sql.join('\n'));
const { count } = await supabase.from('venues').select('*', { count: 'exact', head: true });
console.log(`inserted ${inserted}; venues total now ${count}${emitSql ? `; sql -> ${emitSql}` : ''}`);
